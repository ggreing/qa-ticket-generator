import { describe, expect, it } from 'vitest';
import { isNoisePath } from '../../src/preprocess';
import { compileGlob, expandBraces, matchesAny, normalizePath } from '../../src/preprocess/glob';
import {
  basename,
  builtinNoise,
  classifyPath,
  dirname,
  extension,
  firstLines,
  hasGeneratedHeader,
  isConfigPath,
  isTestPath,
} from '../../src/preprocess/noise';

const none = { include: [], exclude: [] };

describe('PRE-02 glob matcher', () => {
  it.each([
    ['**/*.ts', 'src/a/b.ts', true],
    ['**/*.ts', 'b.ts', true],
    ['src/**', 'src/a/b/c.ts', true],
    ['src/**', 'srcx/a.ts', false],
    ['src/**/test/*.ts', 'src/test/a.ts', true],
    ['src/**/test/*.ts', 'src/x/y/test/a.ts', true],
    ['src/*/a.ts', 'src/x/y/a.ts', false],
    ['src/?.ts', 'src/a.ts', true],
    ['src/?.ts', 'src/ab.ts', false],
    ['src/{a,b}/**', 'src/b/x.ts', true],
    ['src/{a,b}/**', 'src/c/x.ts', false],
    ['*.{js,ts}', 'deep/dir/file.js', true],
    ['{a,{b,c}}.md', 'c.md', true],
    ['dist/', 'dist/index.js', true],
    ['/dist/**', 'dist/index.js', true],
    ['./dist/**', 'dist/index.js', true],
    ['dist/**', 'packages/dist/index.js', false],
    ['a\\*b.ts', 'a*b.ts', true],
    ['a\\*b.ts', 'axb.ts', false],
    ['{x}.ts', '{x}.ts', true],
    ['*.SNAP', 'a.snap', false],
    ['**', 'anything/at/all', true],
    ['a/**/b', 'a/b', true],
    ['*a*b*', 'xxaxxbxx', true],
    ['*a*b', 'xxaxxbxx', false],
  ])('%s vs %s → %s', (pattern, path, expected) => {
    expect(compileGlob(pattern)(path)).toBe(expected);
  });

  it('normalizes ./, leading slashes and backslashes in paths', () => {
    expect(normalizePath('./a/b')).toBe('a/b');
    expect(normalizePath('/a/b')).toBe('a/b');
    expect(normalizePath('a\\b\\c.ts')).toBe('a/b/c.ts');
    expect(compileGlob('src/**')('.\\src\\x.ts')).toBe(true);
  });

  it('expands braces in written order and caps the expansion', () => {
    expect(expandBraces('{a,b}{1,2}')).toEqual(['a1', 'a2', 'b1', 'b2']);
    expect(expandBraces('no-braces')).toEqual(['no-braces']);
    expect(expandBraces('{unbalanced')).toEqual(['{unbalanced']);
    expect(expandBraces('{a,b}{c,d}{e,f}{g,h}{i,j}{k,l}{m,n}{o,p}{q,r}').length).toBeLessThanOrEqual(256);
  });

  it('matchesAny is false for an empty list', () => {
    expect(matchesAny('a.ts', [])).toBe(false);
  });
});

describe('PRE-02 noise filter', () => {
  it.each([
    ['package-lock.json', 'noise'],
    ['apps/web/pnpm-lock.yaml', 'noise'],
    ['go.sum', 'noise'],
    ['assets/Logo.PNG', 'binary'],
    ['fonts/a.woff2', 'binary'],
    ['dist/a.js', 'noise'],
    ['packages/x/build/out.js', 'noise'],
    ['app.min.css', 'noise'],
    ['app.js.map', 'noise'],
    ['vendor/x.go', 'noise'],
    ['node_modules/x/index.js', 'noise'],
    ['src/__snapshots__/a.snap', 'noise'],
    ['icons/a.svg', 'noise'],
  ])('PRE-02 drops %s as %s', (path, reason) => {
    expect(builtinNoise(path)?.reason).toBe(reason);
  });

  it.each(['src/app.ts', 'package.json', 'go.mod', 'README.md', 'src/builder.ts', 'src/distance.ts'])(
    'PRE-02 keeps %s',
    (path) => {
      expect(builtinNoise(path)).toBeNull();
    },
  );

  it('PRE-02 exclude > include > built-in list', () => {
    const opts = { exclude: ['src/gen/**'], include: ['dist/keep/**', 'src/gen/keep.ts'] };
    expect(classifyPath('src/gen/a.ts', opts)?.rule).toBe('exclude');
    expect(classifyPath('src/gen/keep.ts', opts)?.rule).toBe('exclude');
    expect(classifyPath('dist/keep/a.js', opts)).toBeNull();
    expect(classifyPath('dist/other.js', opts)?.reason).toBe('noise');
  });

  it('TRG-04 isNoisePath uses the same path rules', () => {
    expect(isNoisePath('yarn.lock', none)).toBe(true);
    expect(isNoisePath('src/a.ts', none)).toBe(false);
    expect(isNoisePath('src/a.ts', { include: [], exclude: ['src/**'] })).toBe(true);
    expect(isNoisePath('dist/a.js', { include: ['dist/**'], exclude: [] })).toBe(false);
  });

  it('PRE-02 detects generated markers only in the first 10 lines', () => {
    expect(hasGeneratedHeader(['// Code generated by x. DO NOT EDIT.'])).toBe(true);
    expect(hasGeneratedHeader(['/** @generated */'])).toBe(true);
    expect(hasGeneratedHeader(['// generated code, please do not edit'])).toBe(false);
    const late = [...Array.from({ length: 10 }, () => 'x'), '// DO NOT EDIT'];
    expect(hasGeneratedHeader(late)).toBe(false);
  });

  it('firstLines reads only the head of large texts', () => {
    expect(firstLines('a\nb\nc', 2)).toEqual(['a', 'b']);
    expect(firstLines('a', 5)).toEqual(['a']);
    expect(firstLines('a\n', 5)).toEqual(['a', '']);
  });

  it('path helpers', () => {
    expect(basename('a/b/c.ts')).toBe('c.ts');
    expect(basename('c.ts')).toBe('c.ts');
    expect(dirname('a/b/c.ts')).toBe('a/b');
    expect(dirname('c.ts')).toBe('');
    expect(extension('a/B.TS')).toBe('ts');
    expect(extension('.env')).toBe('');
    expect(extension('Makefile')).toBe('');
  });
});

